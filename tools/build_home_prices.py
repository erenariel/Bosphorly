#!/usr/bin/env python3
"""Write data/home-prices.json: the few records of data/public-market-prices.json that the home page shows
(its tour cards and the hammam banner), so the home page does not download the whole 1 MB catalogue.

Run it after editing data/public-market-prices.json. tools/check_site.py fails while the two files disagree,
and the Pages deploy runs it too."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Ids the home page looks up: the tour cards (const tours=[...] in index.html) and the hammam banner.
HOME_IDS = ["bb-morning", "bb-sunset", "bb-oldcity", "orient-dinner", "sea-land", "alaturka", "alaturka-massage"]


def build() -> dict:
    src = json.loads((ROOT / "data/public-market-prices.json").read_text(encoding="utf-8"))
    by_id = {r["id"]: r for r in src["records"]}
    missing = [i for i in HOME_IDS if i not in by_id]
    assert not missing, f"Home page records missing from data/public-market-prices.json: {missing}"
    return {
        "checked_at": src["checked_at"],
        "note": "Generated by tools/build_home_prices.py from data/public-market-prices.json. Do not edit by hand.",
        "records": [by_id[i] for i in HOME_IDS],
    }


def text() -> str:
    return json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"


if __name__ == "__main__":
    (ROOT / "data/home-prices.json").write_text(text(), encoding="utf-8")
    print("data/home-prices.json written")
